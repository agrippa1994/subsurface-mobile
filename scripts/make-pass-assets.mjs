// AI-generated (Claude)
// Writes src/lib/wallet/pass-assets.ts: the images every Wallet pass carries and
// Apple's WWDR G4 intermediate certificate the pass signature has to include.
//
// Both are public and fixed, so they are generated once and checked in rather
// than read at runtime: a pass is built on the device, offline, from a module
// the bundler already has.
//
// - The icon is the app icon (assets/images/icon.png) scaled with `sips`, so this
//   script runs on macOS only.
// - The certificate is downloaded from apple.com and pinned by its SHA-256
//   fingerprint, so a changed or intercepted download fails instead of being
//   embedded.
//
// Run: node scripts/make-pass-assets.mjs

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/lib/wallet/pass-assets.ts');

const WWDR_URL = 'https://www.apple.com/certificateauthority/AppleWWDRCAG4.cer';
const WWDR_SHA256 = 'ea4757885538dd8cb59ff4556f676087d83c85e70902c122e42c0808b5bce14c';

// Wallet picks the @2x/@3x variant for the screen; the 1x one is the fallback
// Apple requires. Sizes from the PassKit "Pass Design and Creation" guide.
const ICONS = { 'icon.png': 29, 'icon@2x.png': 58, 'icon@3x.png': 87 };
const LOGOS = { 'logo.png': 50, 'logo@2x.png': 100, 'logo@3x.png': 150 };

function scaled(size, dir) {
  const out = join(dir, `${size}.png`);
  execFileSync('sips', ['-z', String(size), String(size), join(ROOT, 'assets/images/icon.png'), '--out', out], {
    stdio: 'ignore',
  });
  return readFileSync(out).toString('base64');
}

const dir = mkdtempSync(join(tmpdir(), 'pass-assets-'));
try {
  const images = {};
  for (const [name, size] of Object.entries({ ...ICONS, ...LOGOS })) {
    images[name] = scaled(size, dir);
  }

  const response = await fetch(WWDR_URL);
  if (!response.ok) {
    throw new Error(`WWDR download failed: HTTP ${response.status}`);
  }
  const der = Buffer.from(await response.arrayBuffer());
  const fingerprint = createHash('sha256').update(der).digest('hex');
  if (fingerprint !== WWDR_SHA256) {
    throw new Error(`WWDR fingerprint mismatch: ${fingerprint}`);
  }
  const pem = `-----BEGIN CERTIFICATE-----\n${der
    .toString('base64')
    .replace(/(.{64})/g, '$1\n')
    .trim()}\n-----END CERTIFICATE-----`;

  const lines = [
    '// AI-generated (Claude)',
    '// Generated by scripts/make-pass-assets.mjs - do not edit by hand.',
    '',
    '/** Apple Worldwide Developer Relations G4, the issuer of Pass Type ID certificates. */',
    `export const WWDR_G4_PEM = \`${pem}\`;`,
    '',
    '/** The images every pass carries, base64 PNG keyed by their name in the pass bundle. */',
    'export const PASS_IMAGES: Readonly<Record<string, string>> = {',
    ...Object.entries(images).map(([name, data]) => `  '${name}': '${data}',`),
    '};',
    '',
  ];
  writeFileSync(OUT, lines.join('\n'));
  console.log(`wrote ${OUT}`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
